a = [1, 2, 3, 4, 5, 6]
b = [4, 5, 6, 7, 8, 9]

set1 = set(a)
set2 = set(b)

c = set1 ^ set2
d = set1 | set2
e = set1 & set2

print("Исходный список 1:", a)
print("Исходный список 2:", b)
print("Уникальные для каждого списка:", list(c))
print("Уникальные для объединения:", list(d))
print("Содержащиеся в обоих списках:", list(e))